#!/usr/bin/env python3
"""Cut APRS symbols out of the APRSdroid sprite sheet (res/drawable-nodpi/allicons.png, GPLv2, aprs.fi artwork)
and write LVGL 9 RGB565A8 const image descriptors to src/ui/icons/aprs/.
Usage: tools/gen_aprs_icons.py <aprsdroid_checkout_dir>
Sheet layout: 16 columns, 64 px cells, 6 rows per page; page 0 = primary table '/', cell index = ord(code) - 33.
NAMES must follow the AprsIcon enum order in lib/core/aprs_symbol.h (None excluded)."""
import os, sys
from PIL import Image

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
OUT = os.path.join(ROOT, "src", "ui", "icons", "aprs")
SIZES = [16, 24, 32]  # the 48 px alert icon is the 32 px bitmap scaled 1.5x in alert_overlay.cpp
# (enum name, primary-table code). Lora has no APRSdroid art: it reuses '&' (gateway).
SYMS = [("House", "-"), ("Car", ">"), ("Human", "["), ("Digi", "#"), ("Repeater", "r"), ("Laptop", "l"), ("Wx", "_"),
        ("Ship", "s"), ("Ambulance", "a"), ("Bike", "b"), ("Icp", "c"), ("Fire", "d"), ("Firetruck", "f"),
        ("Hospital", "h"), ("Yagi", "y"), ("Glider", "g"), ("Truck", "k"), ("BigTruck", "u"), ("Van", "v"),
        ("HamClock", "V"), ("Rover", "p"), ("Eoc", "o"), ("TruckStop", "t"), ("MicERepeater", "m"), ("Node", "n"),
        ("Grid", "q"), ("Lora", "&")]

def cell(sheet, code):
    i = ord(code) - 33
    x, y = (i % 16) * 64, (i // 16) * 64
    return sheet.crop((x, y, x + 64, y + 64))

def rgb565a8(im, n):
    im = im.convert("RGBa").resize((n, n), Image.LANCZOS).convert("RGBA")  # premultiplied resize: no dark fringes
    rgb, a = bytearray(), bytearray()
    d = im.tobytes()
    for r, g, b, al in zip(d[0::4], d[1::4], d[2::4], d[3::4]):
        v = ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3)
        rgb += bytes((v & 0xFF, v >> 8))
        a.append(al)
    return bytes(rgb + a)

def main():
    if len(sys.argv) != 2:
        sys.exit(__doc__)
    sheet = Image.open(os.path.join(sys.argv[1], "res", "drawable-nodpi", "allicons.png")).convert("RGBA")
    os.makedirs(OUT, exist_ok=True)
    total = 0
    hdr = ["// Generated by tools/gen_aprs_icons.py - do not edit.",
           "// APRS symbol artwork from APRSdroid (https://github.com/ge0rg/aprsdroid, GPL-2.0), aprs.fi symbol set.",
           "#pragma once", '#include "lvgl.h"', "#ifdef __cplusplus", 'extern "C" {', "#endif"]
    for n in SIZES:
        lines = ["// Generated by tools/gen_aprs_icons.py - do not edit.",
                 "// APRS symbol artwork from APRSdroid (https://github.com/ge0rg/aprsdroid, GPL-2.0), aprs.fi symbol set.",
                 '#include "aprs_icons.h"']
        for name, code in SYMS:
            px = rgb565a8(cell(sheet, code), n)
            total += len(px)
            sym = "aprs_%s_%d" % (name.lower(), n)
            lines.append("static const uint8_t %s_map[] __attribute__((aligned(4))) = {" % sym)
            for i in range(0, len(px), 24):
                lines.append("  " + ",".join("0x%02x" % b for b in px[i:i + 24]) + ",")
            lines += ["};", "static const lv_image_dsc_t %s = {" % sym,
                      "  .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565A8, .flags = 0, .w = %d, .h = %d, .stride = %d}," % (n, n, n * 2),
                      "  .data_size = sizeof(%s_map), .data = %s_map };" % (sym, sym)]
        lines.append("const lv_image_dsc_t* const aprs_icons_%d[APRS_ICON_COUNT] = {" % n)
        lines += ["  &aprs_%s_%d," % (name.lower(), n) for name, _ in SYMS]
        lines.append("};")
        open(os.path.join(OUT, "aprs_icons_%d.c" % n), "w").write("\n".join(lines) + "\n")
        hdr.append("extern const lv_image_dsc_t* const aprs_icons_%d[];" % n)
    hdr.insert(4, "#define APRS_ICON_COUNT %d  // AprsIcon enum minus None; index = enum - 1" % len(SYMS))
    hdr += ["#ifdef __cplusplus", "}", "#endif"]
    open(os.path.join(OUT, "aprs_icons.h"), "w").write("\n".join(hdr) + "\n")
    print("%d symbols x %s px, %d bytes" % (len(SYMS), SIZES, total))

main()
