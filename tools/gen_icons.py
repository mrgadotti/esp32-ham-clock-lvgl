#!/usr/bin/env python3
"""Convert the dark-theme 50x50 weather BMPs (no 'w' suffix) into LVGL 9 RGB565 const image descriptors.
Usage: tools/gen_icons.py [icon50_dir]   (default ../ESP32-HAM-CLOCK/data/icon50 relative to the repo root)"""
import os, struct, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(ROOT, "..", "ESP32-HAM-CLOCK", "data", "icon50")
OUT = os.path.join(ROOT, "src", "ui", "icons")
NAMES = ["200", "300", "500", "502", "511", "520", "600", "611", "700", "800", "800n", "801", "801n", "803", "wind"]
LIMIT = 80 * 1024

def bmp_rgb565(path):
    d = open(path, "rb").read()
    off, = struct.unpack_from("<I", d, 10)
    w, h, _, bpp = struct.unpack_from("<iiHH", d, 18)
    assert d[:2] == b"BM" and bpp == 24 and w == 50 and abs(h) == 50, path
    stride = (w * 3 + 3) & ~3
    out = bytearray()
    for y in range(50):
        row = off + (49 - y) * stride if h > 0 else off + y * stride  # bottom-up unless h < 0
        for x in range(50):
            b, g, r = d[row + x * 3: row + x * 3 + 3]
            out += struct.pack("<H", ((r & 0xF8) << 8) | ((g & 0xFC) << 3) | (b >> 3))
    return bytes(out)

total = 0
hdr = ["#pragma once", "#include \"lvgl.h\"", "#ifdef __cplusplus", "extern \"C\" {", "#endif"]
for n in NAMES:
    px = bmp_rgb565(os.path.join(SRC, n + ".bmp"))
    total += len(px)
    sym = "wxicon_" + n
    lines = ["// Generated by tools/gen_icons.py - do not edit.", '#include "lvgl.h"',
             "static const uint8_t %s_map[] __attribute__((aligned(4))) = {" % sym]
    for i in range(0, len(px), 24):
        lines.append("  " + ",".join("0x%02x" % b for b in px[i:i + 24]) + ",")
    lines += ["};", "const lv_image_dsc_t %s = {" % sym,
              "  .header = {.magic = LV_IMAGE_HEADER_MAGIC, .cf = LV_COLOR_FORMAT_RGB565, .flags = 0, .w = 50, .h = 50, .stride = 100},",
              "  .data_size = sizeof(%s_map), .data = %s_map };" % (sym, sym)]
    open(os.path.join(OUT, n + ".c"), "w").write("\n".join(lines) + "\n")
    hdr.append("extern const lv_image_dsc_t %s;" % sym)
if total > LIMIT:
    sys.exit("icons total %d bytes > %d" % (total, LIMIT))
hdr += ["#ifdef __cplusplus", "}", "#endif", "// Maps an OpenWeather condition id to an icon; nullptr when unknown.",
        "#ifdef __cplusplus", "const lv_image_dsc_t* weatherIcon(int id, bool night);", "#endif"]
open(os.path.join(OUT, "weather_icons.h"), "w").write("\n".join(hdr) + "\n")
print("%d icons, %d bytes" % (len(NAMES), total))
